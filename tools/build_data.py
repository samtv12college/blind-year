"""Turns Robert Shiller's monthly S&P data (datasets/s-and-p-500, ODC-PDDL-1.0) into data.js.

Usage: python3 -I tools/build_data.py raw/shiller.csv data.js
Keeps 1871-01 through the last month where price, dividend, CPI and the 10-year rate are all present.
"""
import csv, json, sys

src, out = sys.argv[1], sys.argv[2]
rows = []
with open(src, newline="") as f:
    for r in csv.DictReader(f):
        p, d, cpi, rate, pe = (float(r[k]) for k in ("SP500", "Dividend", "Consumer Price Index", "Long Interest Rate", "PE10"))
        if p <= 0 or d <= 0 or cpi <= 0 or rate <= 0:
            break
        rows.append((r["Date"][:7], p, d, cpi, rate, pe))

first = rows[0][0]
cols = list(zip(*rows))
data = {
    "start": first,
    "end": rows[-1][0],
    "price": [round(x, 4) for x in cols[1]],
    "div": [round(x, 4) for x in cols[2]],
    "cpi": [round(x, 3) for x in cols[3]],
    "rate": [round(x, 3) for x in cols[4]],
    "cape": [round(x, 2) for x in cols[5]],
}
with open(out, "w") as f:
    f.write("// Generated by tools/build_data.py from Robert Shiller's monthly data\n")
    f.write("// (github.com/datasets/s-and-p-500, ODC-PDDL-1.0). Do not edit by hand.\n")
    f.write("var SHILLER = " + json.dumps(data, separators=(",", ":")) + ";\n")
print(f"{len(rows)} months, {first} to {rows[-1][0]}")
